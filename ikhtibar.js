  /* ---------- التطبيع (تجاهل التشكيل والهمزات والتاء المربوطة) ---------- */
  const DIACRITICS = /[\u064B-\u0652\u0670\u0640\u0653-\u0655\u06D6-\u06ED\u200C-\u200F\u0610-\u061A]/;
  function normChar(ch) {
    if (ch === "أ" || ch === "إ" || ch === "آ" || ch === "ٱ") return "ا";
    if (ch === "ى") return "ي";
    if (ch === "ة") return "ه";
    if (ch === "ؤ") return "و";
    if (ch === "ئ") return "ي";
    return ch;
  }
  function stripped(text) {
    let out = "";
    const map = [];
    for (let i = 0; i < text.length; i++) {
      const ch = text[i];
      if (DIACRITICS.test(ch)) continue;
      out += normChar(ch);
      map.push(i);
    }
    return { text: out, map };
  }
  function normalize(s) { return stripped(String(s == null ? "" : s)).text; }
  function escapeHtml(s) {
    return String(s).replace(/[&<>"']/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;", '"': "&quot;", "'": "&#39;" }[c]));
  }
  function arNum(n) {
    return String(n).replace(/\d/g, (d) => "٠١٢٣٤٥٦٧٨٩"[+d]);
  }

  /* تظليل الجواب داخل نصّ الدليل */
  function highlightAnswer(verseText, answer) {
    const s = stripped(verseText);
    const na = normalize(answer);
    if (!na) return escapeHtml(verseText);
    const idx = s.text.indexOf(na);
    if (idx < 0) return escapeHtml(verseText);
    const start = s.map[idx];
    const end = s.map[idx + na.length - 1] + 1;
    return escapeHtml(verseText.slice(0, start)) +
      "<mark>" + escapeHtml(verseText.slice(start, end)) + "</mark>" +
      escapeHtml(verseText.slice(end));
  }

